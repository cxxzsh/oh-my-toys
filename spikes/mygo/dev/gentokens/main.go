// Command gentokens turns design/tokens.json (copied from the design-system
// artifact) into ds/tokens_gen.go, so that every color, type size, radius,
// spacing, shadow and layout size in the UI comes from the tokens file and
// nothing is typed by hand.
//
//	go run ./dev/gentokens            (or: go generate ./internal/ui/ds)
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"strconv"
	"strings"
)

type token struct {
	Name  string          `json:"name"`
	Value json.RawMessage `json:"value"`
}

type style struct {
	Name          string `json:"name"`
	FontSize      string `json:"fontSize"`
	LineHeight    string `json:"lineHeight"`
	FontWeight    int    `json:"fontWeight"`
	Family        string `json:"family"`
	LetterSpacing string `json:"letterSpacing"`
}

type file struct {
	Version int `json:"version"`
	Color   struct {
		Tokens []token `json:"tokens"`
	} `json:"color"`
	Type struct {
		Groups []struct {
			Styles []style `json:"styles"`
		} `json:"groups"`
	} `json:"type"`
	Spacing struct{ Tokens []token } `json:"spacing"`
	Radius  struct{ Tokens []token } `json:"radius"`
	Shadow  struct{ Tokens []token } `json:"shadow"`
	Size    struct{ Tokens []token } `json:"size"`
}

func main() {
	in, out := "design/tokens.json", "internal/ui/ds/tokens_gen.go"
	if len(os.Args) == 3 {
		in, out = os.Args[1], os.Args[2]
	}
	f, err := load(in)
	if err != nil {
		log.Fatal(err)
	}
	if err := write(out, generate(f)); err != nil {
		log.Fatal(err)
	}
}

func load(path string) (file, error) {
	var f file
	raw, err := os.ReadFile(path) //nolint:gosec // G304: the developer names the tokens file to read
	if err != nil {
		return f, fmt.Errorf("read tokens: %w", err)
	}
	if err := json.Unmarshal(raw, &f); err != nil {
		return f, fmt.Errorf("parse %s: %w", path, err)
	}
	return f, nil
}

// printer writes formatted Go source into a buffer.
type printer struct{ bytes.Buffer }

func (b *printer) p(format string, a ...any) {
	_, _ = fmt.Fprintf(b, format, a...) // a bytes.Buffer grows rather than fails
}

func generate(f file) []byte {
	var b printer
	b.p("// Code generated by dev/gentokens from design/tokens.json (version %d). DO NOT EDIT.\n\n", f.Version)
	b.p("package ds\n\nimport \"github.com/egoist/mygo/ui\"\n\n")
	b.colors(f.Color.Tokens)
	b.types(f)
	b.scalars("Spacing", f.Spacing.Tokens)
	b.scalars("Radii", f.Radius.Tokens)
	b.scalars("Layout sizes", f.Size.Tokens)
	b.shadows(f.Shadow.Tokens)
	return b.Bytes()
}

func themes() []string { return []string{"light", "dark"} }

// colors writes a struct with a field per color token, and its light and
// dark values.
func (b *printer) colors(tokens []token) {
	b.p("// Palette holds every color token of one theme.\ntype Palette struct {\n")
	for _, t := range tokens {
		b.p("\t%s ui.Color // %s\n", ident(t.Name), t.Name)
	}
	b.p("}\n\n")
	for _, theme := range themes() {
		b.p("// %s is the %s theme.\nvar %s = Palette{\n", ident(theme), theme, ident(theme))
		for _, t := range tokens {
			b.p("\t%s: %s,\n", ident(t.Name), color(themed(t.Value, theme)))
		}
		b.p("}\n\n")
	}
}

func (b *printer) types(f file) {
	b.p("// TypeStyle is a text style of the type scale.\ntype TypeStyle struct {\n\tSize, LineHeight float32\n\tWeight int\n\tDisplay, Mono bool\n\tTracking float32 // em\n}\n\n")
	b.p("var (\n")
	for _, g := range f.Type.Groups {
		for _, s := range g.Styles {
			b.p("\t%s = TypeStyle{Size: %s, LineHeight: %s, Weight: %d, Display: %v, Mono: %v, Tracking: %s}\n",
				ident(s.Name), px(s.FontSize), px(s.LineHeight), s.FontWeight, s.Family == "display",
				s.Family == "mono" || s.Name == "mono", em(s.LetterSpacing))
		}
	}
	b.p(")\n\n")
}

func (b *printer) scalars(doc string, tokens []token) {
	b.p("// %s.\nconst (\n", doc)
	for _, t := range tokens {
		var s string
		_ = json.Unmarshal(t.Value, &s)
		b.p("\t%s = %s\n", ident(t.Name), px(s))
	}
	b.p(")\n\n")
}

// shadows writes the shadow tokens as lists of layers, per theme.
func (b *printer) shadows(tokens []token) {
	b.p("// Shadow is one layer of a CSS box-shadow.\ntype Shadow struct {\n\tX, Y, Blur, Spread float32\n\tColor ui.Color\n}\n\n")
	b.p("// Shadows holds the shadow tokens of one theme.\ntype Shadows struct {\n")
	for _, t := range tokens {
		b.p("\t%s []Shadow\n", ident(t.Name))
	}
	b.p("}\n\n")
	for _, theme := range themes() {
		b.p("var %sShadows = Shadows{\n", ident(theme))
		for _, t := range tokens {
			b.p("\t%s: %s,\n", ident(t.Name), shadows(themed(t.Value, theme)))
		}
		b.p("}\n\n")
	}
}

func write(path string, src []byte) error {
	formatted, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("format generated code: %w", err)
	}
	if err := os.WriteFile(path, formatted, 0o600); err != nil { //nolint:gosec // G703: the developer names the file to write
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

// themed returns a token's value for a theme: a plain string serves both.
func themed(v json.RawMessage, theme string) string {
	var s string
	if json.Unmarshal(v, &s) == nil {
		return s
	}
	var m map[string]string
	if err := json.Unmarshal(v, &m); err != nil {
		log.Fatalf("value %s: %v", v, err)
	}
	if s, ok := m[theme]; ok {
		return s
	}
	return m["light"] // e.g. on-accent has one value for both
}

var rgba = regexp.MustCompile(`rgba\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*\)`)

func color(s string) string {
	s = strings.TrimSpace(s)
	if strings.HasPrefix(s, "#") {
		return fmt.Sprintf("ui.Hex(%q)", s)
	}
	if m := rgba.FindStringSubmatch(s); m != nil {
		return fmt.Sprintf("ui.RGBA(%s, %s, %s, %s)", m[1], m[2], m[3], m[4])
	}
	log.Fatalf("color %q", s)
	return ""
}

func shadows(s string) string {
	if strings.TrimSpace(s) == "none" {
		return "nil"
	}
	var layers []string
	// Split on commas outside parentheses.
	depth, start := 0, 0
	var parts []string
	for i, r := range s {
		switch r {
		case '(':
			depth++
		case ')':
			depth--
		case ',':
			if depth == 0 {
				parts = append(parts, s[start:i])
				start = i + 1
			}
		}
	}
	parts = append(parts, s[start:])
	for _, part := range parts {
		part = strings.TrimSpace(part)
		i := strings.Index(part, "rgba")
		if i < 0 {
			i = strings.Index(part, "#")
		}
		nums := strings.Fields(part[:i])
		for len(nums) < 4 {
			nums = append(nums, "0")
		}
		layers = append(layers, fmt.Sprintf("{%s, %s, %s, %s, %s}", px(nums[0]), px(nums[1]), px(nums[2]), px(nums[3]), color(part[i:])))
	}
	return "[]Shadow{" + strings.Join(layers, ", ") + "}"
}

func px(s string) string {
	s = strings.TrimSuffix(strings.TrimSpace(s), "px")
	if _, err := strconv.ParseFloat(s, 32); err != nil {
		log.Fatalf("length %q", s)
	}
	return s
}

func em(s string) string {
	if s == "" {
		return "0"
	}
	return strings.TrimSuffix(s, "em")
}

// ident turns "bg-window" into "BgWindow".
func ident(s string) string {
	var b strings.Builder
	for _, w := range strings.FieldsFunc(s, func(r rune) bool { return r == '-' || r == '_' }) {
		b.WriteString(strings.ToUpper(w[:1]) + w[1:])
	}
	return b.String()
}
